def get_service_config() -> Dict:
    """Retorna configuração para templates de serviço."""
    paths = get_jarvis_paths()
    user = getpass.getuser()
    
    if platform.system().lower() == "windows":
        python_exec = paths.venv / "Scripts" / "python.exe"
        venv_bin = str(paths.venv / "Scripts")
        group = "Users"
    else:
        python_exec = paths.venv / "bin" / "python"
        venv_bin = str(paths.venv / "bin")
        group = getpass.getuser()
    
    return {
        "user": user,
        "group": group,
        "working_dir": str(paths.base),
        "python_exec": str(python_exec),
        "venv": str(paths.venv),
        "venv_bin": venv_bin,
        "system_path": os.environ.get("PATH", ""),
        "config_file": str(paths.config_file),
        "log_dir": str(paths.logs),
        "service_name": "JARVIS",
        "label": "com.jarvis.cyberbot",
    }


def install_systemd_service(config: Dict = None) -> bool:
    """Instala serviço systemd (Linux)."""
    if platform.system().lower() != "linux":
        return False
    
    config = config or get_service_config()
    
    try:
        # Render template
        template = Template(SYSTEMD_TEMPLATE)
        content = template.substitute(config)
        
        # Write to /etc/systemd/system/
        service_path = Path("/etc/systemd/system/jarvis.service")
        service_path.write_text(content)
        
        # Reload systemd
        subprocess.run(["systemctl", "daemon-reload"], check=True, timeout=10)
        
        # Enable service
        subprocess.run(["systemctl", "enable", "jarvis"], check=True, timeout=10)
        
        print("[Service] systemd service installed and enabled")
        return True
    except subprocess.CalledProcessError as e:
        print(f"[Service] systemd error: {e}")
        return False
    except Exception as e:
        print(f"[Service] Error: {e}")
        return False


def install_nssm_service(config: Dict = None) -> bool:
    """Instala serviço Windows via NSSM."""
    if platform.system().lower() != "windows":
        return False
    
    config = config or get_service_config()
    
    # Check if NSSM is available
    nssm_path = shutil.which("nssm")
    if not nssm_path:
        # Try to download NSSM
        if not _download_nssm():
            print("[Service] NSSM not found. Download from https://nssm.cc/download")
            return False
        nssm_path = str(Path.cwd() / "nssm.exe")
    
    try:
        # Render template
        template = Template(NSSM_TEMPLATE)
        content = template.substitute(config)
        
        # Write batch file
        bat_path = Path(config["working_dir"]) / "install_service.bat"
        bat_path.write_text(content)
        
        # Run batch
        result = subprocess.run([str(bat_path)], capture_output=True, text=True, timeout=30)
        if result.returncode != 0:
            print(f"[NSSM] Error: {result.stderr}")
            return False
        
        # Start service
        subprocess.run(["nssm", "start", "JARVIS"], check=True, timeout=10)
        
        print("[Service] NSSM service installed and started")
        return True
    except Exception as e:
        print(f"[Service] NSSM error: {e}")
        return False


def _download_nssm() -> bool:
    """Baixa NSSM para Windows."""
    import urllib.request
    import zipfile
    import tempfile
    
    try:
        url = "https://nssm.cc/release/nssm-2.24.zip"
        with tempfile.TemporaryDirectory() as tmp:
            zip_path = Path(tmp) / "nssm.zip"
            urllib.request.urlretrieve(url, zip_path)
            
            with zipfile.ZipFile(zip_path, 'r') as zf:
                # Extract nssm.exe (x64)
                for name in zf.namelist():
                    if name.endswith("nssm.exe") and "64" in name:
                        zf.extract(name, ".")
                        # Move to current dir
                        extracted = Path(tmp) / name
                        shutil.move(str(extracted), "nssm.exe")
                        return True
    except Exception as e:
        print(f"[NSSM] Download failed: {e}")
    return False


def install_launchd_service(config: Dict = None) -> bool:
    """Instala LaunchAgent macOS."""
    if platform.system().lower() != "darwin":
        return False
    
    config = config or get_service_config()
    
    try:
        template = Template(LAUNCHD_TEMPLATE)
        content = template.substitute(config)
        
        plist_path = Path.home() / "Library" / "LaunchAgents" / "com.jarvis.cyberbot.plist"
        plist_path.parent.mkdir(parents=True, exist_ok=True)
        plist_path.write_text(content)
        
        # Load agent
        subprocess.run(["launchctl", "load", str(plist_path)], check=True, timeout=10)
        
        print("[Service] LaunchAgent installed and loaded")
        return True
    except Exception as e:
        print(f"[Service] LaunchAgent error: {e}")
        return False


def uninstall_service() -> bool:
    """Remove serviço instalado."""
    system = platform.system().lower()
    
    try:
        if system == "linux":
            subprocess.run(["systemctl", "disable", "jarvis"], timeout=10)
            subprocess.run(["systemctl", "stop", "jarvis"], timeout=10)
            Path("/etc/systemd/system/jarvis.service").unlink(missing_ok=True)
            subprocess.run(["systemctl", "daemon-reload"], timeout=10)
        
        elif system == "windows":
            subprocess.run(["nssm", "stop", "JARVIS"], timeout=10)
            subprocess.run(["nssm", "remove", "JARVIS", "confirm"], timeout=10)
        
        elif system == "darwin":
            plist = Path.home() / "Library" / "LaunchAgents" / "com.jarvis.cyberbot.plist"
            subprocess.run(["launchctl", "unload", str(plist)], timeout=10)
            plist.unlink(missing_ok=True)
        
        return True
    except Exception as e:
        print(f"[Service] Uninstall error: {e}")
        return False


